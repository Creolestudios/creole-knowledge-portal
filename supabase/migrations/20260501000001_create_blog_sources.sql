-- Tracks target web feeds/URLs configured by administrators to extract
-- morning technical articles and engineering updates.
-- ==========================================

CREATE TABLE IF NOT EXISTS public.blog_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    added_by UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Index for source lookups
CREATE INDEX IF NOT EXISTS idx_blog_sources_url ON public.blog_sources (url);
CREATE INDEX IF NOT EXISTS idx_blog_sources_added_by ON public.blog_sources (added_by);

-- Enable Row Level Security
ALTER TABLE public.blog_sources ENABLE ROW LEVEL SECURITY;

-- Idempotent RLS Policies
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'blog_sources'
          AND policyname = 'Allow authenticated users to read blog sources'
    ) THEN
        CREATE POLICY "Allow authenticated users to read blog sources"
            ON public.blog_sources
            FOR SELECT
            TO authenticated
            USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'blog_sources'
          AND policyname = 'Allow admins to insert blog sources'
    ) THEN
        CREATE POLICY "Allow admins to insert blog sources"
            ON public.blog_sources
            FOR INSERT
            TO authenticated
            WITH CHECK (
                EXISTS (
                    SELECT 1 FROM public.user_profiles
                    WHERE user_profiles.user_id = auth.uid()
                      AND user_profiles.role = 'admin'
                )
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'blog_sources'
          AND policyname = 'Allow admins to delete blog sources'
    ) THEN
        CREATE POLICY "Allow admins to delete blog sources"
            ON public.blog_sources
            FOR DELETE
            TO authenticated
            USING (
                EXISTS (
                    SELECT 1 FROM public.user_profiles
                    WHERE user_profiles.user_id = auth.uid()
                      AND user_profiles.role = 'admin'
                )
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'blog_sources'
          AND policyname = 'Service role full access on blog_sources'
    ) THEN
        CREATE POLICY "Service role full access on blog_sources"
            ON public.blog_sources
            USING (true)
            WITH CHECK (true);
    END IF;
END
$$;

